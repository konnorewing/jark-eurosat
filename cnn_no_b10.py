plt.bar(model_names, accuracies)
plt.ylabel('Validation Accuracy (%)')
plt.title('Model Comparision - B10 Removed')
plt.ylim(0,100)

for i, a in enumerate(accuracies):
  plt.text(i, a + 1, f'{a:.2f}%', ha='center')

plt.show()

# Test different ensemble weights
weights = np.linspace(0, 1, 21)
weight_accuracies = []

for w in weights:
  # Combine CNN and spatial pooling probabilities
  probs = w * cnn_probs + (1 - w) * spatial_probs
  pred = np.argmax(probs, axis=1)

  # Calculate validation accuracy
  accuracy = accuracy_score(test_labels, pred)
  weight_accuracies.append(accuracy)

  print(f'CNN: {w:.2f}, Spatial: {1-w:.2f}, Accuracy: {accuracy*100:.2f}%')

# Identify the best weight combination
best_index = np.argmax(weight_accuracies)
best_weight = weights[best_index]

print('\nBest CNN weight:', best_weight)
print('Best Spatial Pooling weight', 1 - best_weight)
print('Best ensemble accuracy:', max(weight_accuracies)*100)

plt.figure(figsize=(9, 5))
plt.plot(weights, np.array(weight_accuracies)*100, marker='o')
plt.axvline(best_weight, color='red', linestyle='--', label = f'Optimal CNN weight: {best_weight:.2f}')

plt.xlabel('CNN Weight')
plt.ylabel('Validation Accuracy (%)')
plt.title('Effect of Ensemble Weight on Classification Accuracy')
plt.legend()
