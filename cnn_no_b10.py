# 1. Load

# Load the data
with h5py.File(path + '/train.mat', 'r') as f:
  satellite_images = f['X'][:].transpose(3, 2, 1, 0)
  land_cover_labels=f['y'][:].ravel().astype(int) - 1

  bands = [''.join(chr(c) for c in row).strip()
  for row in f['bands'][:].T] # decode spectral band names

  classes = [''.join(chr(c) for c in row).strip()
  for row in f['classes'][:].T] # decode land-cover class names

  print("Bands:", bands)
  print("Classes:", classes)

# Check the data
print("Label values:", np.unique(land_cover_labels))
